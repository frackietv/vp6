def test_settings_providers():
    store = settings.MemorySettings()
    settings.use(lambda: store)
    try:
        claude.rename_session("abc", "  My session ")
        assert store.values == {"claude/titles/abc": "My session"}
        assert claude.session_title("abc") == "My session"
        claude.rename_session("abc", "")
        assert store.values == {}
    finally:
        settings.use(None)
    assert settings.settings() is not store  # (the default again: the IDE's)


