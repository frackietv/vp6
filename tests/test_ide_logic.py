def test_claude_protocol():
    written = []
    protocol = claude.ClaudeProtocol(written.append, mode="plan")
    assert protocol.arguments()[-2:] == ["--permission-mode", "plan"]
    seen = []
    protocol.message.connect(lambda data: seen.append(data["type"]))
    protocol.sessionChanged.connect(lambda session: seen.append(session))
    protocol.permissionRequested.connect(lambda *args: seen.append(args))
    protocol.send("Hi")
    assert json.loads(written[-1])["message"]["content"][0]["text"] == "Hi"
    protocol.feed(b'{"type": "system", "session_id": "s1"}\n{"type": "control_request", '
                  b'"request_id": "r1", "request": {"subtype": "can_use_tool", '
                  b'"tool_name": "Bash", "input": {"command": "ls"}}}\n{"type": "res')
    assert seen == ["s1", "system", ("r1", "Bash", {"command": "ls"})]
    protocol.answer("r1", True, {"command": "ls"}, always="Bash")
    protocol.feed(b'ult"}\n{"type": "control_request", "request_id": "r2", "request": '
                  b'{"subtype": "can_use_tool", "tool_name": "Bash", "input": {}}}\n')
    assert seen[-1] == "result"
    assert json.loads(written[-1])["response"]["request_id"] == "r2"  # (always allowed)
    assert protocol.arguments()[-2:] == ["--resume", "s1"]
    assert claude.parse_auth_status(0, '{"loggedIn": true, "email": "a@b.c"}') == \
        (True, "Logged in as a@b.c")


def test_codex_rpc_and_chat():
    written = []
    rpc = codex.JsonRpc(written.append)
    answers = []
    rpc.request("initialize", {}, lambda result: rpc.initialized())
    rpc.request("thread/list", {}, answers.append)
    assert len(written) == 1  # (waits for initialize)
    rpc.feed(b'{"id": 1, "result": {}}\n')
    assert [json.loads(w).get("method") for w in written] == [
        "initialize", "initialized", "thread/list"]
    rpc.feed(b'{"id": 2, "result": {"data": []}}\n')
    assert answers == [{"data": []}]

    class Server:
        generation, running = 1, True

        def __init__(self):
            self.requests = []

        def request(self, method, params, callback=None, error=None):
            self.requests.append(method)
            if method == "thread/start":
                callback({"thread": {"id": "t1"}, "model": "m"})
            elif method == "turn/start":
                callback({"turn": {"id": "u1"}})

    server = Server()
    chat = codex.CodexChatCore(server, "/tmp")
    busy = []
    chat.busyChanged.connect(busy.append)
    assert chat.send("Hello")
    assert server.requests == ["thread/start", "turn/start"] and chat.session_id == "t1"
    chat.notified("turn/completed", {"threadId": "t1"})
    assert busy == [True, False] and chat.model == "m"


def test_debug_protocol():
    written = []
    protocol = debugging.DebugProtocol(written.append, {"/p/a.py": [3]})
    protocol.pause()
    assert written == []  # (not connected yet)
    protocol.connect()
    assert json.loads(written[0]) == {"cmd": "start", "breakpoints": {"/p/a.py": [3]},
                                      "step": False}
    paused, results = [], []
    protocol.paused.connect(paused.append)
    protocol.feed(b'{"event": "paused", "reason": "breakpoint", "file": "/p/a.py", '
                  b'"line": 3}\n')
    assert protocol.is_paused and debugging.describe(paused[0]) == \
        "Breakpoint at a.py, line 3"
    protocol.evaluate("x", results.append)
    assert json.loads(written[-1])["expr"] == "x"
    protocol.feed(b'{"event": "result", "id": 1, "value": "1", "type": "int"}\n')
    assert results == [{"event": "result", "id": 1, "value": "1", "type": "int"}]
    protocol.disconnect()
    assert not protocol.is_paused


