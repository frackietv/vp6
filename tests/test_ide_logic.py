def test_themes_in_a_settings_object():
    store = settings.MemorySettings()
    state = themes.read_settings(store)
    assert state.selection == themes.SYSTEM and set(state.themes) == {"Light", "Dark"}
    custom = themes.Theme("Mine", True, dict(themes.BUILTIN_THEMES["Dark"].colors),
                          dict(themes.BUILTIN_THEMES["Dark"].syntax))
    custom.colors["background"] = "#101010"
    state.themes["Mine"] = custom
    state.selection, state.font_size = "Mine", 15
    themes.write_settings(state, store)
    assert set(json.loads(store.values["editor/themes"])) == {"Mine"}  # (only what differs)
    again = themes.read_settings(store)
    assert again.selection == "Mine" and again.font_size == 15
    assert themes.resolve(again, system_dark=False).colors["background"] == "#101010"
    assert themes.app_is_dark(again, system_dark=False)
    again.selection = themes.SYSTEM
    assert themes.resolve(again, system_dark=False).name == "Light"


