ROOT = os.path.dirname(os.path.dirname(os.path.abspath(vp6.__file__)))
LOGIC = os.path.join(ROOT, "vp6", "ide", "logic")


def test_no_qt_when_imported(tmp_path):
    """Imported on their own (vp6's __init__, which loads the controls, left
    out), with PySide6 and shiboken6 refused, the logic modules load."""
    modules = sorted("vp6.ide.logic." + name[:-3] for name in os.listdir(LOGIC)
                     if name.endswith(".py") and name != "__init__.py")
    script = textwrap.dedent(f"""
        import importlib, importlib.abc, sys, types

        class NoQt(importlib.abc.MetaPathFinder):
            def find_spec(self, name, path=None, target=None):
                if name.split(".")[0] in ("PySide6", "shiboken6"):
                    raise ImportError(f"{{name}} imported")
                return None

        sys.meta_path.insert(0, NoQt())
        package = types.ModuleType("vp6")
        package.__path__ = [{os.path.join(ROOT, "vp6")!r}]
        package.__version__ = "x"
        sys.modules["vp6"] = package
        for name in {modules + ["vp6.formfile", "vp6.project"]!r}:
            importlib.import_module(name)
        from vp6.ide.logic import outline, search
        assert outline.outline("X = 1\\ndef f():\\n    pass\\n")[1].name == "f"
        found, result = search.find_all([("a.py", "x = 1\\n")], search.SearchOptions("x"))
        assert len(found) == 1, found
        print("no Qt:", len(sys.modules) > 0, "PySide6" in sys.modules)
    """)
    result = subprocess.run([sys.executable, "-c", script], capture_output=True, text=True,
                            timeout=60, cwd=str(tmp_path))
    assert result.returncode == 0, result.stderr
    assert result.stdout.strip() == "no Qt: True False"


