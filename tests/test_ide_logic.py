FORM = '''from vp6 import *


class Form1(Form):
    # region VP6 Designer - generated by the form designer, do not edit
    def InitializeComponent(self):
        self.Caption = 'Hello'
    # endregion

    def cmdHello_Click(self):
        MsgBox("Hello")
'''


def test_search_in_texts():
    files = [("Form1.py", FORM), ("Module1.py", "# 😀 Hello\nhello = 'hello'\n")]
    found, result = search.find_all(files, search.SearchOptions("hello"))
    assert result.found and result.message == "6 matches in 2 files"
    emoji = [f for f in found if f.path == "Module1.py"]
    assert (emoji[0].start, emoji[0].line, emoji[0].text) == (5, 1, "# 😀 Hello")  # (UTF-16)
    found, _ = search.find_all(files, search.SearchOptions("hello", match_case=True),
                               only="Module1.py")
    assert [(f.line, f.start) for f in found] == [(2, 11), (2, 20)]
    # The next match round the project, and the wrapping message
    options = search.SearchOptions("Hello", match_case=True)
    match, result = search.next_in_project(files, "Module1.py", (5, 10), options)
    assert match.path == "Form1.py" and match.line == 7 and "Passed the end" in result.message
    match, result = search.next_in_project(files, None, (0, 0), options, backward=True)
    assert match.path == "Module1.py"
    # Replace All leaves the designer region alone
    changed, result = search.replace_all_in_project(files, search.SearchOptions("hello",
                                                                                replace="Bye"))
    assert "skipped 1 in designer regions" in result.message
    assert "self.Caption = 'Hello'" in changed["Form1.py"]
    assert 'MsgBox("Bye")' in changed["Form1.py"]
    assert changed["Module1.py"] == "# 😀 Bye\nBye = 'Bye'\n"
    _, result = search.replace_all_in_project(files, search.SearchOptions("(", regex=True))
    assert not result.found and "Invalid regular expression" in result.message


