class _View:
    """A chat window as logic.chats sees it: what it was told to show."""

    def __init__(self):
        self.shown, self.state = [], ""

    def show_text(self, who, text):
        self.shown.append((who, text))

    def show_tool(self, name, summary):
        self.shown.append(("tool", name, summary))

    def show_tool_error(self, text):
        self.shown.append(("tool error", text))

    def show_error(self, text):
        self.shown.append(("error", text))

    def set_state(self, text):
        self.state = text

    def state_text(self):
        return self.state


def test_chat_messages_shown_in_a_view(tmp_path):
    from vp6.ide.logic import chats

    view = _View()
    messages = chats.ClaudeMessages(view)
    messages.show_message({"type": "system", "subtype": "init", "model": "m1"})
    assert view.state == "Model: m1"
    messages.show_message({"type": "assistant", "message": {"content": [
        {"type": "text", "text": "Hi **there**"},
        {"type": "tool_use", "id": "t", "name": "Bash", "input": {"command": "ls  -a"}}]}})
    messages.show_message({"type": "user", "message": {"content": [
        {"type": "tool_result", "is_error": True, "content": [{"type": "text", "text": "no"}]}]}})
    messages.show_message({"type": "result", "subtype": "success", "is_error": True,
                           "result": "Please run /login", "total_cost_usd": 0.5})
    assert view.shown == [("assistant", "Hi **there**"), ("tool", "Bash", "ls -a"),
                          ("tool error", "no"), ("error", "Please run /login")]
    assert view.state == "Done ($0.5000)" and chats.login_hint("Please run /login")
    assert chats.files_may_have_changed_claude({"type": "result"})
    view = _View()
    messages = chats.CodexMessages(view, str(tmp_path))
    messages.show_thread({"turns": [{"items": [
        {"type": "userMessage", "content": [{"type": "text", "text": "Make it"}]},
        {"type": "fileChange", "status": "completed", "changes": [
            {"path": str(tmp_path / "a.py"), "kind": {"type": "add"}}]},
        {"type": "commandExecution", "command": "/bin/sh -lc 'make'", "status": "failed",
         "exitCode": 2, "commandActions": [{"command": "make"}], "aggregatedOutput": "x\nbad"},
        {"type": "agentMessage", "text": " Done. "}]}]})
    assert view.shown == [("user", "Make it"), ("tool", "Add", "a.py"), ("tool", "Shell", "make"),
                          ("tool error", "bad"), ("assistant", "Done.")]
    assert view.state.startswith("Resumed")
    messages.show_message({"method": "error", "params": {"error": {"message": "gone"}}})
    messages.show_message({"method": "turn/completed", "params": {"turn": {"status": "failed"}}})
    assert view.shown[-1] == ("error", "gone")
    assert chats.files_may_have_changed_codex({"method": "item/completed", "params": {
        "item": {"type": "fileChange"}}})
