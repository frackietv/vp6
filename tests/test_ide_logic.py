class _Doc:
    def __init__(self, text, name="Form1"):
        from vp6 import formfile

        self.text, self.name = text, name
        self.form_def = formfile.parse(text) if formfile.is_form_source(text) else None
        self.kind = self.form_def.kind if self.form_def else "module"


def test_code_window_model(qapp):
    form = FORM.replace("self.Caption = 'Hello'",
                        "self.Caption = 'Hello'\n        self.cmdHello = CommandButton(self)")
    doc = _Doc(form)
    names = [name for name, _events in codewindow.objects(doc)]
    assert names == ["Form", "cmdHello"]
    assert codewindow.handlers_written(doc, "cmdHello") == ["Click"]
    assert codewindow.default_event(doc, "Form") == "Load"
    assert codewindow.procedure_at(doc, 11) == ("cmdHello", "Click")
    assert codewindow.procedure_at(doc, 0) == (codewindow.GENERAL, codewindow.DECLARATIONS)
    line, stub = codewindow.handler_stub(doc, "Form", "Load")
    assert line == form.split("\n").index('        MsgBox("Hello")')
    assert stub.startswith("\n\n    def Form_Load(self):")
    assert codewindow.handler_stub(doc, "cmdHello", "Click") is None  # (there already)
    assert "cmdHello" in codewindow.complete("self.", doc)
    assert "Caption" in codewindow.complete("self.cmdHello.", doc)
    module = _Doc("def Main():\n    helper()\n\n\ndef helper():\n    pass\n", "Module1")
    assert codewindow.objects(module) == [] and codewindow.def_line(module.text, "helper") == 4
    assert codewindow.general_procedures(module) == ["Main", "helper"]


def test_menu_entries(qapp):
    from vp6 import formfile

    source = formfile.new_form_source("Form1")
    form_def = formfile.parse(source)
    entries = [menus.MenuEntry(0, "&File", "mnuFile"), menus.MenuEntry(1, "E&xit", "mnuExit",
                                                                      shortcut="Ctrl+Q")]
    assert menus.validate(entries, set()) is None
    assert "indented more than one level" in menus.validate(
        [menus.MenuEntry(0, "a", "a"), menus.MenuEntry(2, "b", "b")], set())
    form_def.controls = menus.menu_defs(entries)
    again = menus.entries_from(form_def)
    assert [(e.level, e.caption, e.shortcut) for e in again] == [
        (0, "&File", ""), (1, "E&xit", "Ctrl+Q")]


