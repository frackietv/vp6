"""Kitchen Sink page: OpenGLView (drawn with OpenGL in its Paint event, Animate repaints it
30 times a second) and QuickView (a Qt Quick user interface written in QML, talking to the
form: context values in, QmlEvent and vp6.set out)."""

import colorsys
import math

from vp6 import *

GL_COLOR_BUFFER_BIT, GL_SCISSOR_TEST = 0x4000, 0x0C11

QML = """import QtQuick

Rectangle {
    id: root
    color: "#1f5fbf"
    radius: 8
    signal tapped(int x, int y)
    Text {
        anchors.centerIn: parent
        text: "Hello from QML, " + context.name + "!\\nClick me"
        horizontalAlignment: Text.AlignHCenter
        color: "white"
        font.pixelSize: 18
    }
    MouseArea {
        anchors.fill: parent
        onClicked: (mouse) => {
            root.tapped(mouse.x, mouse.y)
            vp6.set("lblSet", "Caption", "vp6.set: clicked at " + Math.round(mouse.x) + ", " +
                    Math.round(mouse.y))
        }
    }
}
"""


class pgGL(Form):
    # region VP6 Designer - generated by the form designer, do not edit
    def InitializeComponent(self):
        self.Caption = 'OpenGL and QML'
        self.Width = 640
        self.Height = 440
        self.glvSpin = OpenGLView(self, Left=16, Top=16, Width=296, Height=260, FrameRate=30,
                                  Animate=True, TabIndex=1,
                                  ToolTipText='An OpenGLView: its Paint event draws with OpenGL')
        self.lblGL = Label(self, Caption='', Left=16, Top=284, Width=296, Height=44, WordWrap=True,
                           TabIndex=2)
        self.qmlHello = QuickView(self, Left=328, Top=16, Width=296, Height=260, TabIndex=3,
                                  ToolTipText='A QuickView: QML, made in Form_Load')
        self.lblQml = Label(self, Caption='', Left=328, Top=284, Width=296, Height=44,
                            WordWrap=True, TabIndex=4)
        self.lblSet = Label(self, Caption='', Left=328, Top=336, Width=296, Height=22, TabIndex=6)
        self.chkAnimate = CheckBox(self, Caption='&Animate', Left=16, Top=340, Width=120,
                                   Height=25, Value=1, TabIndex=5)
    # endregion

    def Form_Load(self):
        self.qmlHello.Context["name"] = App.Title or "VP6"  # (context.name in QML)
        self.qmlHello.QmlText = QML

    def glvSpin_InitializeGL(self):
        self.lblGL.Caption = "InitializeGL: OpenGL is ready"

    def glvSpin_Paint(self):
        gl = self.glvSpin.GL  # Qt's OpenGL functions (or: from OpenGL.GL import *)
        if gl is None:
            return
        t = self.glvSpin.ElapsedTime
        r, g, b = colorsys.hsv_to_rgb((t / 6) % 1, 0.5, 0.9)
        gl.glDisable(GL_SCISSOR_TEST)
        gl.glClearColor(0.12, 0.12, 0.16, 1)
        gl.glClear(GL_COLOR_BUFFER_BIT)
        ratio = self.glvSpin.PixelRatio  # (OpenGL counts the screen's pixels)
        size = int(80 * ratio)
        x = int((self.glvSpin.Width * ratio - size) * (0.5 + 0.4 * math.sin(t)))
        gl.glEnable(GL_SCISSOR_TEST)  # a square: the cleared part of the window
        gl.glScissor(x, int(90 * ratio), size, size)
        gl.glClearColor(r, g, b, 1)
        gl.glClear(GL_COLOR_BUFFER_BIT)
        gl.glDisable(GL_SCISSOR_TEST)

    def chkAnimate_Click(self):
        self.glvSpin.Animate = self.chkAnimate.Value == vpChecked
        self.lblGL.Caption = f"{self.glvSpin.FrameCount} frames so far"

    def qmlHello_QmlEvent(self, Name, Args):
        self.lblQml.Caption = f"QmlEvent: {Name}{tuple(Args)}"


if __name__ == "__main__":
    run(pgGL)
