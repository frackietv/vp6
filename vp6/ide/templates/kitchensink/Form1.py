    def txtPassword_LostFocus(self):
        self.lblStatus.Caption = f"The password has {len(self.txtPassword.Text)} characters"

    def txtUpper_KeyPress(self, KeyAscii):
        # Returning a character code replaces the typed key (0 would swallow it)
        return ord(chr(KeyAscii).upper())

