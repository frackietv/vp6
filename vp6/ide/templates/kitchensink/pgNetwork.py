"""Kitchen Sink page: TCP connections with Winsock controls (a server listening on
a free port, a client connecting to it, the connection taken by an element of a
control array, an echo: what the client sends comes back in capitals) and a
FileWatcher telling when a file changes (FileChanged) or files come and go in a
folder (FolderChanged)."""

import os
import time

from vp6 import *

# The folder and file the FileWatcher watches (made in the project's folder)
FOLDER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "watched")
NOTES = os.path.join(FOLDER, "notes.txt")


class pgNetwork(Form):
    # region VP6 Designer - generated by the form designer, do not edit
    def InitializeComponent(self):
        self.Caption = 'Network and files'
        self.Width = 640
        self.Height = 440
        self.fraNet = Frame(self, Caption='Winsock: a server and a client', Left=16, Top=8,
                            Width=608, Height=206, TabIndex=1)
        self.cmdListen = CommandButton(self.fraNet, Caption='&Listen', Left=12, Top=26, Width=110,
                                       Height=30, TabIndex=2,
                                       ToolTipText='The server listens on a free port (LocalPort 0)')
        self.cmdConnect = CommandButton(self.fraNet, Caption='&Connect', Left=130, Top=26,
                                        Width=110, Height=30, Enabled=False, TabIndex=3,
                                        ToolTipText='The client connects to the server')
        self.txtSend = TextBox(self.fraNet, Text='hello, server', Left=248, Top=29, Width=230,
                               Height=25, TabIndex=4)
        self.cmdSend = CommandButton(self.fraNet, Caption='&Send', Left=486, Top=26, Width=110,
                                     Height=30, Default=True, Enabled=False, TabIndex=5,
                                     ToolTipText='SendData: the server sends it back in capitals')
        self.lstNet = ListBox(self.fraNet, Left=12, Top=64, Width=584, Height=130, TabIndex=6)
        self.fraFiles = Frame(self, Caption='FileWatcher', Left=16, Top=222, Width=608, Height=170,
                              TabIndex=7)
        self.cmdWrite = CommandButton(self.fraFiles, Caption='&Write notes.txt', Left=12, Top=26,
                                      Width=150, Height=30, TabIndex=8,
                                      ToolTipText='Change the watched file: FileChanged')
        self.cmdAdd = CommandButton(self.fraFiles, Caption='&Add a file', Left=170, Top=26,
                                    Width=120, Height=30, TabIndex=9,
                                    ToolTipText='A new file in the watched folder: FolderChanged')
        self.chkWatch = CheckBox(self.fraFiles, Caption='&Report changes', Left=300, Top=29,
                                 Width=160, Height=25, Value=1, TabIndex=10,
                                 ToolTipText='Enabled: off holds the events back')
        self.lstFiles = ListBox(self.fraFiles, Left=12, Top=64, Width=584, Height=94, TabIndex=11)
        self.lblHint = Label(self,
                             Caption='Edit watched/notes.txt in another program too: the FileWatcher sees it (also when the editor replaces the file).',
                             Left=16, Top=398, Width=440, Height=36, WordWrap=True, TabIndex=12)
        self.wskServer = Winsock(self, Left=480, Top=400)
        self.wskPeer = ControlArray()
        self.wskPeer[0] = Winsock(self, Left=516, Top=400)
        self.wskClient = Winsock(self, Left=552, Top=400, RemoteHost='127.0.0.1')
        self.fwNotes = FileWatcher(self, Left=588, Top=400)
    # endregion

    def Form_Load(self):
        os.makedirs(FOLDER, exist_ok=True)
        if not os.path.exists(NOTES):
            with open(NOTES, "w", encoding="utf-8") as file:
                file.write("Notes\n")
        self.fwNotes.Add(NOTES)  # a file: changed, replaced or removed
        self.fwNotes.Add(FOLDER)  # a folder: files added, removed, renamed
        self.files_added = 0

    def net(self, text):
        self.lstNet.AddItem(text)
        self.lstNet.ListIndex = self.lstNet.ListCount - 1

    # --- the server: listens, and a control array element takes each connection --------------
    def cmdListen_Click(self):
        self.wskServer.Bind(0, "127.0.0.1")  # any free port (it tells which), from here only
        self.wskServer.Listen()
        self.net(f"Server: listening on port {self.wskServer.LocalPort} (vpSckListening: "
                 f"{self.wskServer.State == vpSckListening})")
        self.cmdListen.Enabled = False
        self.cmdConnect.Enabled = True

    def wskServer_ConnectionRequest(self, RequestID):
        index = len(self.wskPeer)
        Load(self.wskPeer, index)  # a Winsock of its own for this connection
        self.wskPeer[index].Accept(RequestID)
        self.net(f"Server: connection {RequestID} accepted by wskPeer({index})")

    def wskPeer_DataArrival(self, Index, BytesTotal):
        text = self.wskPeer[Index].GetData()
        self.net(f"Server got {BytesTotal} bytes: {text!r}; sending it back in capitals")
        self.wskPeer[Index].SendData(text.upper())

    def wskPeer_Close(self, Index):
        self.net(f"Server: wskPeer({Index}) was closed by the client")
        self.wskPeer[Index].Close()

    # --- the client -----------------------------------------------------------------------------
    def cmdConnect_Click(self):
        if self.wskClient.State == vpSckConnected:
            self.wskClient.Close()  # (the server's Close event fires)
            self.cmdConnect.Caption = "&Connect"
            self.cmdSend.Enabled = False
            self.net("Client: closed")
            return
        self.wskClient.Connect(RemotePort=self.wskServer.LocalPort)
        self.net(f"Client: connecting to {self.wskClient.RemoteHost}:"
                 f"{self.wskClient.RemotePort}")

    def wskClient_Connect(self):
        self.net(f"Client: connected (its IP: {self.wskClient.LocalIP})")
        self.cmdConnect.Caption = "Dis&connect"
        self.cmdSend.Enabled = True

    def cmdSend_Click(self):
        self.wskClient.SendData(self.txtSend.Text)

    def wskClient_DataArrival(self, BytesTotal):
        self.net(f"Client got: {self.wskClient.GetData()!r}")

    def wskClient_Error(self, Number, Description):
        self.net(f"Client: error {Number}: {Description}")

    # --- the FileWatcher ------------------------------------------------------------------------
    def files(self, text):
        self.lstFiles.AddItem(f"{time.strftime('%H:%M:%S')}  {text}")
        self.lstFiles.ListIndex = self.lstFiles.ListCount - 1

    def cmdWrite_Click(self):
        with open(NOTES, "a", encoding="utf-8") as file:
            file.write(f"A line at {time.strftime('%H:%M:%S')}\n")

    def cmdAdd_Click(self):
        self.files_added += 1
        with open(os.path.join(FOLDER, f"new {self.files_added}.txt"), "w") as file:
            file.write("new\n")

    def chkWatch_Click(self):
        self.fwNotes.Enabled = self.chkWatch.Value == vpChecked

    def fwNotes_FileChanged(self, Path):
        lines = open(Path, encoding="utf-8").read().count("\n") if os.path.exists(Path) else 0
        self.files(f"FileChanged: {os.path.basename(Path)} ({lines} lines)")

    def fwNotes_FolderChanged(self, Path):
        names = sorted(os.listdir(Path)) if os.path.isdir(Path) else []
        self.files(f"FolderChanged: {os.path.basename(Path)} has {', '.join(names)}")


if __name__ == "__main__":
    run(pgNetwork)
