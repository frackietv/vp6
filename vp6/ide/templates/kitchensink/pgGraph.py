"""Kitchen Sink page: Graph, a coordinate plane for mathematics: functions (as text or
Python), points to drag along a line and a curve, π on the axis, polar and parametric
curves, inequalities, a number line, statistics, answers placed with the mouse and
checked by vp6edu.answers, and the graphics methods over it all."""

import math
import random

from vp6 import *
from vp6edu.answers import Inequality, Point

SHOWS = ("Functions and points", "Trigonometry", "Inequalities", "Number line",
         "Place a point", "Statistics", "Scatter plot")


class pgGraph(Form):
    # region VP6 Designer - generated by the form designer, do not edit
    def InitializeComponent(self):
        self.Caption = 'Graph'
        self.Width = 640
        self.Height = 440
        self.grfMath = Graph(self, Left=16, Top=16, Width=440, Height=360, TabIndex=1,
                             ToolTipText='Drag the plane to move it; the wheel zooms')
        self.lblShow = Label(self, Caption='Show:', Left=472, Top=16, Width=152, Height=22,
                             TabIndex=2)
        self.cboShow = ComboBox(self, Style=2, Left=472, Top=40, Width=152, Height=25, TabIndex=3)
        self.cmdFit = CommandButton(self, Caption='&Fit', Left=472, Top=80, Width=74, Height=32,
                                    TabIndex=4, ToolTipText='ZoomToFit: show everything plotted')
        self.cmdReset = CommandButton(self, Caption='&Reset', Left=550, Top=80, Width=74,
                                      Height=32, TabIndex=5,
                                      ToolTipText='ResetView: the view it started with')
        self.cmdCheck = CommandButton(self, Caption='C&heck', Left=472, Top=120, Width=152,
                                      Height=32, Enabled=False, TabIndex=6,
                                      ToolTipText='Check the answer placed on the graph')
        self.cmdCopy = CommandButton(self, Caption='&Copy', Left=472, Top=160, Width=152,
                                     Height=32, TabIndex=7,
                                     ToolTipText='EditCopy: the graph on the clipboard, as a picture')
        self.lblInfo = Label(self, Caption='Click the plane', Left=16, Top=388, Width=608,
                             Height=40, WordWrap=True, TabIndex=8)
    # endregion

    task = ""  # (what the Check button checks)

    def Form_Load(self):
        for name in SHOWS:
            self.cboShow.AddItem(name)
        self.cboShow.ListIndex = 0

    def cboShow_Click(self):
        grf = self.grfMath
        grf.Clear()
        grf.Cls()
        grf.PlaceMode = vpPlaceNone
        grf.Mode = vpGraphPlane
        grf.PiTicks = False
        grf.XLabel, grf.YLabel = "x", "y"
        self.task = ""
        getattr(self, "show_" + str(self.cboShow.ListIndex))()
        self.cmdCheck.Enabled = bool(self.task)

    def show_0(self):
        """Functions as text and as Python, a line through two points you drag, a point
        sliding along a curve, and a hole."""
        grf = self.grfMath
        grf.Scale(-8, 7, 8, -7)
        self.parabola = grf.AddFunction("x^2/4 - 3", Label="$y = \\frac{x^2}{4} - 3$")
        grf.AddFunction(lambda x: 1 / (x - 5), Style=vpDash)  # (its asymptote left open)
        self.a = grf.AddPoint(-4, -2, Draggable=True, Label="A")
        self.b = grf.AddPoint(2, 3, Draggable=True, Label="B")
        grf.AddLine(self.a, self.b)  # (follows A and B)
        self.p = grf.AddPoint(3, On=self.parabola, Draggable=True, Label="P")
        grf.AddPoint(-6, 0, Open=True, Color=vpRed)  # (a hole)
        grf.AddLabel("Drag A, B and P", -7.5, 6.3)
        self.grfMath_PointMoved(self.a)

    def show_1(self):
        grf = self.grfMath
        grf.Scale(-2 * math.pi, 2.2, 2 * math.pi, -2.2)
        grf.PiTicks = True
        grf.AddFunction(math.sin, Label="sin x")
        grf.AddFunction("cos x", Label="cos x", Style=vpDash)
        grf.AddPolar("1 + cos θ", Label="cardioid")  # (r of θ)
        grf.AddParametric("cos t", "sin t", Width=1)  # (the unit circle)
        grf.AddVector(0, 0, math.cos(1), math.sin(1), Label="$e^{i}$")
        self.lblInfo.Caption = "PiTicks numbers the X axis in multiples of π"

    def show_2(self):
        grf = self.grfMath
        grf.Scale(-6, 5, 6, -5)
        grf.AddInequality("y < 2x + 1")  # (dashed: strict)
        grf.AddInequality("x^2 + y^2 <= 9")  # (solid edge)
        grf.AddRegion("x^2/3", "x - 1", 0, 2)  # (between two curves)
        self.lblInfo.Caption = "AddInequality shades where it holds; AddRegion between curves"

    def show_3(self):
        grf = self.grfMath
        grf.Mode = vpGraphNumberLine
        grf.Scale(-6, 1, 6, -1)
        grf.PlaceMode = vpPlaceInterval
        self.task = "-2 < x <= 3"
        self.lblInfo.Caption = f"Show {self.task}: drag along the line; click an end to open " \
                               "or close it, then Check"

    def show_4(self):
        grf = self.grfMath
        grf.Scale(-6, 5, 6, -5)
        grf.PlaceMode = vpPlacePoint
        self.task = "(3, -2)"
        self.lblInfo.Caption = f"Click to place the point {self.task}, then Check"

    def show_5(self):
        grf = self.grfMath
        grf.Mode = vpGraphData
        grf.XLabel, grf.YLabel = "Height (cm)", "Students"
        rng = random.Random(6)
        heights = [round(rng.gauss(168, 9)) for _ in range(80)]
        bars = grf.AddHistogram(heights, Bins=list(range(140, 201, 10)))
        grf.AddBoxPlot(heights, Y=max(bars.Counts) + 3, Height=2)
        grf.ZoomToFit()
        box = grf.Items(2)
        self.lblInfo.Caption = f"Median {box.Median}, quartiles {box.Q1} and {box.Q3}; " \
                               f"{len(bars.Counts)} bins"

    def show_6(self):
        grf = self.grfMath
        grf.Mode = vpGraphData
        grf.XLabel, grf.YLabel = "Hours studied", "Score"
        rng = random.Random(2)
        hours = [rng.uniform(0, 10) for _ in range(25)]
        scores = [min(100, 45 + 5 * h + rng.gauss(0, 6)) for h in hours]
        fit = grf.AddScatter(hours, scores, FitLine=True)
        grf.AddDotPlot([1, 2, 2, 3, 3, 3])  # (a dot plot too: values stacked)
        grf.ZoomToFit()
        self.lblInfo.Caption = f"Fitted line: y = {fit.Slope:.2f}x + {fit.Intercept:.1f}, " \
                               f"r = {fit.Correlation:.2f}"

    def grfMath_Click(self, X, Y):
        if not self.task:
            self.lblInfo.Caption = f"Click({X:.2f}, {Y:.2f}): where you clicked, in the " \
                                   "graph's coordinates"

    def grfMath_PointMoved(self, Item):
        if self.cboShow.ListIndex == 0 and isinstance(Item, GraphItem):
            run = self.b.X - self.a.X
            slope = "undefined" if run == 0 else f"{(self.b.Y - self.a.Y) / run:g}"
            self.lblInfo.Caption = f"The slope of AB is {slope}; P is at ({self.p.X:g}, " \
                                   f"{self.p.Y:g})"
            self.grfMath.Refresh()

    def grfMath_Paint(self):
        # The graphics methods draw in the graph's coordinates: P's drop to the X axis
        if self.cboShow.ListIndex == 0:
            grf = self.grfMath
            grf.DrawStyle = vpDot
            grf.Line(self.p.X, 0, self.p.X, self.p.Y, RGB(128, 128, 128))
            grf.DrawStyle = vpSolid

    def cmdCheck_Click(self):
        answer = self.grfMath.Answer
        if answer is None:
            self.lblInfo.Caption = "Place your answer on the graph first"
            return
        kind = Inequality(self.task) if self.grfMath.PlaceMode == vpPlaceInterval \
            else Point(3, -2)
        result = kind.check(answer)
        self.lblInfo.Caption = f"{result.status.capitalize()}: {result.message}"

    def cmdFit_Click(self):
        self.grfMath.ZoomToFit()

    def cmdReset_Click(self):
        self.grfMath.ResetView()

    def cmdCopy_Click(self):
        self.grfMath.EditCopy()
        self.lblInfo.Caption = "The graph is on the clipboard"


if __name__ == "__main__":
    run(pgGraph)
