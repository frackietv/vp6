"""Kitchen Sink page: designing a form in a program. A DesignerView shows
frmDialog.py, a form of this project, as the IDE's designer does: select, move
and resize its controls, draw new ones with a tool from the list (or double-click one: DropControl),
undo, Align and Make Same Size (the selection to the last one selected); its
events are listed (FormRenamed too). Beside it, VP6's control metadata: the Toolbox's categories
and controls (ControlCategories, ControlTypes), and what one is (ControlInfo: its
icon, description, properties and events)."""

import os

from vp6 import *

FORM = os.path.join(os.path.dirname(os.path.abspath(__file__)), "frmDialog.py")


class pgDesigner(Form):
    # region VP6 Designer - generated by the form designer, do not edit
    def InitializeComponent(self):
        self.Caption = 'Designing forms'
        self.Width = 640
        self.Height = 440
        self.cboCategory = ComboBox(self, Style=2, Left=16, Top=16, Width=180, Height=26,
                                    TabIndex=1, ToolTipText="ControlCategories: the Toolbox's")
        self.lstTypes = ListBox(self, Left=16, Top=48, Width=180, Height=170, TabIndex=2,
                                ToolTipText='ControlTypes: click one to draw it on the form')
        self.picIcon = PictureBox(self, Left=16, Top=226, Width=48, Height=48, BorderStyle=0,
                                  TabIndex=3, ToolTipText='ControlInfo(...).Icon')
        self.lblInfo = Label(self, Caption='', Left=70, Top=226, Width=126, Height=130,
                             WordWrap=True, TabIndex=4)
        self.cmdUndo = CommandButton(self, Caption='&Undo', Left=16, Top=364, Width=86, Height=28,
                                     TabIndex=5)
        self.cmdRedo = CommandButton(self, Caption='&Redo', Left=110, Top=364, Width=86, Height=28,
                                     TabIndex=6)
        self.lblSelected = Label(self, Caption='', Left=16, Top=400, Width=180, Height=32,
                                 WordWrap=True, TabIndex=7)
        self.dsgForm = DesignerView(self, Left=204, Top=16, Width=420, Height=320, TabIndex=8)
        self.lstEvents = ListBox(self, Left=204, Top=342, Width=420, Height=90, TabIndex=9)
    # endregion

    def Form_Load(self):
        for category in ControlCategories():
            self.cboCategory.AddItem(category)
        self.cboCategory.ListIndex = 0
        self.dsgForm.FileName = FORM  # (changes stay here: nothing is saved)
        self.dsgForm_SelChange()
        self.event("Select two or more controls, then double-click here: Align, MakeSameSize")

    # --- the control metadata ---------------------------------------------------------------
    def cboCategory_Click(self):
        self.lstTypes.Clear()
        for name in ControlTypes(self.cboCategory.Text):
            self.lstTypes.AddItem(name)

    def lstTypes_Click(self):
        info = ControlInfo(self.lstTypes.Text)
        self.picIcon.Picture = info.Icon
        events = ", ".join(e.Name for e in info.Events[:4])
        self.lblInfo.Caption = (f"{info.Name}: {len(info.Properties)} properties; events "
                                f"{events}...; {info.DefaultSize[0]} x {info.DefaultSize[1]}")
        self.dsgForm.Tool = info.Name  # the next drag on the form draws one
        self.event(f"Tool = {info.Name}: drag on the form to draw one")

    # --- the designer and its events ------------------------------------------------------------
    def event(self, text):
        self.lstEvents.AddItem(text)
        self.lstEvents.ListIndex = self.lstEvents.ListCount - 1

    def dsgForm_SelChange(self):
        names = self.dsgForm.SelectedControls
        self.lblSelected.Caption = "Selected: " + (", ".join(names) or "the form")

    def dsgForm_ControlAdded(self, Name):
        self.event(f"ControlAdded: {Name} ({self.dsgForm.ControlType(Name)})")

    def dsgForm_ControlDeleted(self, Name):
        self.event(f"ControlDeleted: {Name}")

    def dsgForm_ControlMoved(self, Name):
        left, top = (self.dsgForm.GetProperty(Name, p) for p in ("Left", "Top"))
        self.event(f"ControlMoved: {Name} to {left}, {top}")

    def dsgForm_ControlResized(self, Name):
        self.event(f"ControlResized: {Name}")

    def dsgForm_PropertyChanged(self, Name, Property):
        self.event(f"PropertyChanged: {Name or 'the form'}.{Property}")

    def dsgForm_GoToCode(self, Name, Event):
        self.event(f"GoToCode: {Name or 'Form'}_{Event} (a double-click)")

    def dsgForm_FormRenamed(self, OldName, NewName):
        self.event(f"FormRenamed: {OldName} to {NewName}")

    def lstTypes_DblClick(self):
        name = self.dsgForm.DropControl(self.lstTypes.Text, 120, 120)
        self.event(f"DropControl: {name} at 120, 120 in the view")

    def lstEvents_DblClick(self):  # (Align and MakeSameSize, as the Format menu does)
        if len(self.dsgForm.SelectedControls) > 1:
            self.dsgForm.Align("left")
            self.dsgForm.MakeSameSize("both")
            self.event("Align left, MakeSameSize both: as the last one selected")

    def cmdUndo_Click(self):
        if self.dsgForm.CanUndo:
            self.dsgForm.Undo()

    def cmdRedo_Click(self):
        if self.dsgForm.CanRedo:
            self.dsgForm.Redo()


if __name__ == "__main__":
    run(pgDesigner)
