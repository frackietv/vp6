"""A whole-number calculator: two numbers and the four operations. Division gives a
quotient and a remainder; dividing by zero says why it can't be done. The operation
buttons are a control array, so one event handler serves them all."""

from vp6 import *

OPERATIONS = ("+", "−", "×", "÷")


def calculate(a, b, operation):
    """The result of ``a operation b`` as text, for whole numbers."""
    if operation == "+":
        return f"{a:,} + {b:,} = {a + b:,}"
    if operation == "−":
        if b > a:
            return f"{a:,} − {b:,} isn't a whole number: {b:,} is more than {a:,}."
        return f"{a:,} − {b:,} = {a - b:,}"
    if operation == "×":
        return f"{a:,} × {b:,} = {a * b:,}"
    if b == 0:
        return f"{a:,} ÷ 0 is undefined: no number times 0 makes {a:,}."
    quotient, remainder = divmod(a, b)
    return f"{a:,} ÷ {b:,} = {quotient:,}" + (f" R {remainder:,}" if remainder else "")


class Form1(Form):
    # region VP6 Designer - generated by the form designer, do not edit
    def InitializeComponent(self):
        self.Caption = 'Whole-Number Calculator'
        self.Width = 480
        self.Height = 280
        self.txtA = TextBox(self, Text='9744', Left=16, Top=16, Width=200, Height=36, FontSize=16,
                            TabIndex=1)
        self.txtB = TextBox(self, Text='24', Left=262, Top=16, Width=200, Height=36, FontSize=16,
                            TabIndex=2)
        self.cmdOp = ControlArray()
        self.cmdOp[0] = CommandButton(self, Caption='+', Left=16, Top=70, Width=104, Height=44,
                                      FontSize=16, TabIndex=3)
        self.lblResult = Label(self, Caption='', Left=16, Top=134, Width=446, Height=80,
                               WordWrap=True, FontSize=16, TabIndex=4)
    # endregion

    def Form_Load(self):
        for i in range(1, len(OPERATIONS)):
            button = Load(self.cmdOp, i)
            button.Caption = OPERATIONS[i]
            button.Left = self.cmdOp(0).Left + 114 * i
            button.Visible = True

    def cmdOp_Click(self, Index):
        a, b = self.txtA.Text.replace(",", "").strip(), self.txtB.Text.replace(",", "").strip()
        if not (a.isdigit() and b.isdigit()):
            self.lblResult.Caption = "Type two whole numbers."
            return
        self.lblResult.Caption = calculate(int(a), int(b), OPERATIONS[Index])


if __name__ == "__main__":
    run(Form1)
